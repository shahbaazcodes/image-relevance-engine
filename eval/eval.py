#!/usr/usr/bin/env python3
"""Evaluate hybrid search Top-1 Precision against benchmark queries."""

import asyncio
import json
from datetime import UTC, datetime
from pathlib import Path

import httpx

BASE_URL = "http://127.0.0.1:8000/search/hybrid"
EVAL_SET = Path(__file__).parent / "eval_set.json"
OUTPUT_FILE = Path(__file__).resolve().parent.parent / "EVIDENCE.md"


def load_benchmark():
    with open(EVAL_SET) as f:
        return json.load(f)


async def evaluate_query(query: str, expected_category: str, limit: int = 10):
    async with httpx.AsyncClient() as client:
        response = await client.get(BASE_URL, params={"query": query, "limit": limit})
        response.raise_for_status()
        results = response.json()

    top = results[0] if results else None
    is_correct = bool(top and top.get("category", "").lower() == expected_category.lower())
    return {
        "query": query,
        "expected_category": expected_category,
        "top_category": top.get("category") if top else None,
        "results": results,
        "is_correct": is_correct,
    }


async def run_evaluation():
    benchmarks = load_benchmark()
    queries = []
    per_category = {}

    print(f"Loaded {len(benchmarks['benchmark_queries'])} benchmark categories.")

    for category_group in benchmarks["benchmark_queries"]:
        category = category_group["category"]
        print(f"\nEvaluating category: {category} ({len(category_group['queries'])} queries)")
        per_category[category] = {"total": 0, "correct": 0}

        for q in category_group["queries"]:
            result = await evaluate_query(q, category)
            queries.append(result)
            per_category[category]["total"] += 1
            if result["is_correct"]:
                per_category[category]["correct"] += 1

    total = len(queries)
    correct = sum(1 for r in queries if r["is_correct"])
    overall_precision = (correct / total * 100) if total > 0 else 0.0

    per_cat_stats = {}
    for cat, stats in per_category.items():
        prec = (stats["correct"] / stats["total"] * 100) if stats["total"] > 0 else 0.0
        per_cat_stats[cat] = {
            "precision": round(prec, 2),
            "total": stats["total"],
            "correct": stats["correct"],
        }

    # Build the evidence markdown report
    now = datetime.now(UTC).strftime("%Y-%m-%d %H:%M:%S UTC")

    lines = [
        "# EVIDENCE — Hybrid Search Eval Results",
        "",
        f"**Evaluation run:** {now}",
        "**Base URL:** `http://127.0.0.1:8000/search/hybrid`",
        "**Benchmark file:** `eval/eval_set.json`",
        f"**Total queries evaluated:** {total}",
        f"**Overall Top-1 Precision:** {overall_precision:.2f}%",
        f"**Total correct:** {correct}/{total}",
        "",
        "## Per-Category Precision",
        "",
    ]

    for cat, stats in per_cat_stats.items():
        lines.append(
            f"- **{cat}**: **{stats['precision']}%**  ({stats['correct']}/{stats['total']})"
        )

    lines += [
        "",
        "## Raw Test Log",
        "",
    ]

    for i, r in enumerate(queries, 1):
        marker = "✓ CORRECT" if r["is_correct"] else "✗ WRONG"
        expected = r["expected_category"]
        got = r["top_category"]
        lines.append(f'[{i:3d}] {marker} | expected={expected:<6} got={got:<6} | q="{r["query"]}"')

    lines.append("")
    lines.append("---")
    lines.append("*Generated by eval/eval.py — Hybrid Search Top-1 Precision evaluator.*")

    report = "\n".join(lines) + "\n"

    with open(OUTPUT_FILE, "w") as f:
        f.write(report)

    print("\nResults written to:", OUTPUT_FILE)
    print(report)

    return overall_precision, correct, total


if __name__ == "__main__":
    precision, correct, total = asyncio.run(run_evaluation())
